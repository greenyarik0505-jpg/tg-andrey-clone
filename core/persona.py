def check_sensitive_content(text: str) -> bool:
    """Checks if incoming text mentions financial, sensitive, or safety-critical keywords."""
    lower = text.lower()
    for trig in SENSITIVE_TRIGGERS:
        if trig in lower:
            return True
    return False

def post_process_reply(reply: str) -> List[str]:
    """Cleans up LLM reply, removes AI tropes, splits into realistic short human messages."""
    # Strip markdown quotes and brackets
    cleaned = reply.strip().strip('"').strip("'")
    
    # Remove standard assistant phrases if any leaked
    forbidden = [
        "здравствуйте", "приветствую", "чем я могу вам помочь", "конечно!",
        "как искусственный интеллект", "я бот", "я нейросеть"
    ]
    for f in forbidden:
        cleaned = re.sub(rf"(?i){f}[,.]?\s*", "", cleaned)

    cleaned = cleaned.strip()
    if not cleaned:
        cleaned = random.choice(["пон", "ну хз", "круто", "ладно", "чо"])

    # If it ends with period, remove it
    if cleaned.endswith("."):
        cleaned = cleaned[:-1]

    # Decide whether to split into multiple short messages (like a real kid texting)
    # E.g. "норм / а ты чо делаешь"
    sentences = re.split(r"[?!;\n]+", cleaned)
    chunks = [s.strip() for s in sentences if s.strip()]

    if not chunks:
        chunks = [cleaned]

    # Maximum 3 chunks to avoid spamming
    return chunks[:3]
