def post_process_reply(reply: str, split: bool = True) -> list[str]:
    cleaned = reply.strip().strip('"').strip("'").strip()[:1000]
    if not cleaned:
        return []
    if not split:
        return [cleaned]
    parts = [part.strip() for part in re.split(r"\n+|(?<=[!?;.])\s+", cleaned, maxsplit=2)]
    return [part for part in parts if part]
